#!/usr/bin/env python3
"""
Tower of Hanoi -- four discs moved from the left peg to the right in the
fewest possible moves, which is 2^4 - 1 = 15.

The solution is the three-line recursion everyone meets once: to move n
discs, move n - 1 out of the way, move the biggest, move the n - 1 back on
top. The moves here are generated by exactly that, not listed.

Each move takes three frames -- lifted clear of its peg, carried across,
set down -- so 15 moves are 45 frames. Four frames of the starting tower
before and four of the finished one after, flashing, make 53.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from jtkit import Animation, colors as C  # noqa: E402

DELAY = 220
DISCS = 4
PEG_X = (16, 48, 80)                 # right-hand column of each 2px peg
WIDTH = {0: 8, 1: 14, 2: 20, 3: 26}  # disc 0 is the smallest
COLOR = {0: C.CYAN, 1: C.GREEN, 2: C.YELLOW, 3: C.RED}
CARRY_Y = 1                          # top row of a disc in the air
HOLD = 4


def solve(count, source, target, spare, moves):
    if count == 0:
        return
    solve(count - 1, source, spare, target, moves)
    moves.append((source, target))
    solve(count - 1, spare, target, source, moves)


def draw_disc(frame, disc, peg, top, color=None):
    width = WIDTH[disc]
    frame.rect(PEG_X[peg] - width // 2, top, width, 2, color or COLOR[disc], fill=True)


def draw(anim, pegs, carried=None, flash=False):
    """One frame: the stacks, plus optionally a (disc, peg) held in the air."""
    frame = anim.frame()
    frame.hline(0, 15, 96, C.BLUE)
    for x in PEG_X:
        frame.rect(x - 1, 5, 2, 10, C.BLUE, fill=True)
    for peg, stack in enumerate(pegs):
        for level, disc in enumerate(stack):
            draw_disc(frame, disc, peg, 13 - 2 * level, C.WHITE if flash else None)
    if carried:
        draw_disc(frame, carried[0], carried[1], CARRY_Y)


def build():
    moves = []
    solve(DISCS, 0, 2, 1, moves)
    assert len(moves) == 2**DISCS - 1

    pegs = [list(range(DISCS - 1, -1, -1)), [], []]
    anim = Animation(delay=DELAY)
    for _ in range(HOLD):
        draw(anim, pegs)
    for source, target in moves:
        disc = pegs[source].pop()
        assert not pegs[target] or pegs[target][-1] > disc, "larger disc on smaller"
        draw(anim, pegs, (disc, source))
        draw(anim, pegs, (disc, target))
        pegs[target].append(disc)
        draw(anim, pegs)
    for k in range(HOLD):
        draw(anim, pegs, flash=k % 2 == 0)
    return anim


if __name__ == "__main__":
    animation = build()
    out = Path(__file__).resolve().parents[2] / "src/sample/hanoi.jt"
    animation.save(out)
    print(f"{out.name}: {animation.describe()}")
