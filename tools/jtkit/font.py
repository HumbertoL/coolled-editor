def glyph(char, fold_case=True):
    """
    Look up one glyph.

    The font is uppercase only. With ``fold_case`` (the default) lowercase
    input is upper-cased rather than failing, since panel text is almost
    always set in caps.
    """
    if char in FONT_5X7:
        return FONT_5X7[char]
    if fold_case and char.upper() in FONT_5X7:
        return FONT_5X7[char.upper()]
    raise KeyError(
        f"No glyph for {char!r}. Add it to FONT_5X7 in jtkit/font.py "
        f"as {GLYPH_HEIGHT} rows of {GLYPH_WIDTH} characters."
    )


def missing(text, fold_case=True):
    """Which characters of ``text`` the font cannot draw."""
    absent = []
    for char in text:
        try:
            glyph(char, fold_case=fold_case)
        except KeyError:
            absent.append(char)
    return absent


